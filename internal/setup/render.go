const fragmentHeader = `# Generated by Portplane (https://github.com/akamachinecode/portplane).
# Every scan rewrites this file and keeps the portless names you change here.
# To own a task completely, move it into dekit.yaml: Portplane then leaves it alone.
`

// renderFragment writes the tasks as a dekit fragment. Paths in a fragment
// resolve from the fragment's folder (.portplane/), hence the "../".
func renderFragment(tasks []genTask, _ Options) string {
	var b strings.Builder
	b.WriteString(fragmentHeader)
	if len(tasks) == 0 {
		b.WriteString("tasks: {}\n")
		return b.String()
	}
	b.WriteString("tasks:\n")
	envLine := make([]string, len(agentEnv))
	for i, k := range agentEnv {
		envLine[i] = k + ": null"
	}
	for _, t := range tasks {
		if t.Folder {
			fmt.Fprintf(&b, "  %s:\n", t.Path)
			continue
		}
		if t.Comment != "" {
			fmt.Fprintf(&b, "  # %s\n", t.Comment)
		}
		fmt.Fprintf(&b, "  %s:\n", t.Path)
		if t.Label != "" {
			fmt.Fprintf(&b, "    label: %s\n", quote(t.Label))
		}
		if t.Job {
			b.WriteString("    type: job\n")
		}
		fmt.Fprintf(&b, "    cwd: %s\n", quote(fragmentDir(t.Dir)))
		fmt.Fprintf(&b, "    cmd: %s\n", flowList(t.Cmd))
		if len(t.Deps) > 0 {
			fmt.Fprintf(&b, "    deps: %s\n", flowList(t.Deps))
		}
		fmt.Fprintf(&b, "    env: {%s}\n", strings.Join(envLine, ", "))
	}
	return b.String()
}

// fragmentDir turns a folder-relative dir into a fragment-relative one.
func fragmentDir(dir string) string {
	if dir == "." || dir == "" {
		return ".."
	}
	return "../" + dir
}

func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func flowList(items []string) string {
	q := make([]string, len(items))
	for i, it := range items {
		q[i] = quote(it)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// fragEntry is what a previous fragment said about a task.
type fragEntry struct {
	Sig  string
	Name string // the portless name in its command
}

// parseFragment reads a fragment written by renderFragment (or edited by the
// user) into signatures comparable with genTask.signature.
func parseFragment(b []byte) map[string]fragEntry {
	out := map[string]fragEntry{}
	if len(b) == 0 {
		return out
	}
	var doc struct {
		Tasks map[string]*struct {
			Type string   `yaml:"type"`
			Cwd  string   `yaml:"cwd"`
			Cmd  []string `yaml:"cmd"`
			Deps []string `yaml:"deps"`
		} `yaml:"tasks"`
	}
	if yaml.Unmarshal(b, &doc) != nil {
		return out
	}
	for path, t := range doc.Tasks {
		if t == nil || strings.HasSuffix(path, "/") {
			continue
		}
		dir := strings.TrimPrefix(strings.TrimPrefix(t.Cwd, ".."), "/")
		if dir == "" {
			dir = "."
		}
		g := genTask{Path: path, Dir: dir, Cmd: t.Cmd, Deps: t.Deps, Job: t.Type == "job"}
		e := fragEntry{Sig: g.signature()}
		if w := portless.ParseCommand(t.Cmd); w != nil {
			e.Name = w.Name
		}
		out[path] = e
	}
	return out
}

func oldName(old map[string]fragEntry, task string) string {
	return old[task].Name
}

// ensureLoad returns dekit.yaml with a load entry for the fragment, adding it with as
// small an edit as possible: a new file, an appended item in an existing
// block list, or a load: block at the end of the file.
func ensureLoad(before string) (string, error) {
	rel := FragmentRel
	if strings.TrimSpace(before) == "" {
		return "# dekit project: https://dekit.run. Portplane's generated tasks live in " + rel + ".\nload:\n  - " + rel + "\n", nil
	}
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(before), &doc); err != nil {
		return "", fmt.Errorf("dekit.yaml is not valid YAML: %w", err)
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return "", errors.New("dekit.yaml has no top-level mapping")
	}
	top := doc.Content[0]
	var load *yaml.Node
	for i := 0; i+1 < len(top.Content); i += 2 {
		if top.Content[i].Value == "load" {
			load = top.Content[i+1]
		}
	}
	text := before
	if !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	if load == nil {
		return text + "load:\n  - " + rel + "\n", nil
	}
	if load.Kind != yaml.SequenceNode {
		return "", errors.New("dekit.yaml: load is not a list; add " + rel + " to it by hand")
	}
	for _, item := range load.Content {
		if item.Kind == yaml.ScalarNode && strings.TrimPrefix(item.Value, "./") == rel {
			return before, nil
		}
		if item.Kind == yaml.MappingNode {
			for i := 0; i+1 < len(item.Content); i += 2 {
				if item.Content[i].Value == "file" && strings.TrimPrefix(item.Content[i+1].Value, "./") == rel {
					return before, nil
				}
			}
		}
	}
	if load.Style&yaml.FlowStyle != 0 || len(load.Content) == 0 {
		return "", errors.New("dekit.yaml: load is written inline; add " + rel + " to it by hand, or turn it into a block list")
	}
	last := 0
	for _, item := range load.Content {
		if l := maxLine(item); l > last {
			last = l
		}
	}
	lines := strings.SplitAfter(text, "\n")
	indent := strings.Repeat(" ", load.Content[0].Column-3)
	if load.Content[0].Column < 3 {
		indent = ""
	}
	entry := indent + "- " + rel + "\n"
	out := strings.Join(lines[:last], "") + entry + strings.Join(lines[last:], "")
	// Check the edit parses and contains the entry.
	var check struct {
		Load []any `yaml:"load"`
	}
	if err := yaml.Unmarshal([]byte(out), &check); err != nil {
		return "", fmt.Errorf("could not add the load entry safely; add %s to dekit.yaml by hand", rel)
	}
	return out, nil
}

func maxLine(n *yaml.Node) int {
	m := n.Line
	for _, c := range n.Content {
		if l := maxLine(c); l > m {
			m = l
		}
	}
	return m
}
