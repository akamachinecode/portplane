const fragmentHeader = `# Generated by Portplane (https://github.com/akamachinecode/portplane).
# Every scan rewrites this file and keeps the portless names you change here.
# To own a task completely, move it into dekit.yaml: Portplane then leaves it alone.
`

// renderFragment writes the tasks as a dekit fragment. Paths in a fragment
// resolve from the fragment's folder (.portplane/), hence the "../".
func renderFragment(tasks []genTask, _ Options) string {
	var b strings.Builder
	b.WriteString(fragmentHeader)
	if len(tasks) == 0 {
		b.WriteString("tasks: {}\n")
		return b.String()
	}
	b.WriteString("tasks:\n")
	envLine := make([]string, len(agentEnv))
	for i, k := range agentEnv {
		envLine[i] = k + ": null"
	}
	for _, t := range tasks {
		if t.Folder {
			fmt.Fprintf(&b, "  %s:\n", t.Path)
			continue
		}
		if t.Comment != "" {
			fmt.Fprintf(&b, "  # %s\n", t.Comment)
		}
		fmt.Fprintf(&b, "  %s:\n", t.Path)
		if t.Label != "" {
			fmt.Fprintf(&b, "    label: %s\n", quote(t.Label))
		}
		if t.Job {
			b.WriteString("    type: job\n")
		}
		fmt.Fprintf(&b, "    cwd: %s\n", quote(fragmentDir(t.Dir)))
		fmt.Fprintf(&b, "    cmd: %s\n", flowList(t.Cmd))
		if len(t.Deps) > 0 {
			fmt.Fprintf(&b, "    deps: %s\n", flowList(t.Deps))
		}
		fmt.Fprintf(&b, "    env: {%s}\n", strings.Join(envLine, ", "))
	}
	return b.String()
}

// fragmentDir turns a folder-relative dir into a fragment-relative one.
func fragmentDir(dir string) string {
	switch {
	case dir == "." || dir == "":
		return ".."
	case filepath.IsAbs(dir) || filepath.VolumeName(dir) != "":
		return dir // another drive on Windows: no relative path exists
	}
	return "../" + dir
}

func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func flowList(items []string) string {
	q := make([]string, len(items))
	for i, it := range items {
		q[i] = quote(it)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// fragEntry is what a previous fragment said about a task.
type fragEntry struct {
	Sig  string
	Name string // the portless name in its command
}

// parseFragment reads a fragment written by renderFragment (or edited by the
// user) into signatures comparable with genTask.signature.
func parseFragment(b []byte) map[string]fragEntry {
	out := map[string]fragEntry{}
	if len(b) == 0 {
		return out
	}
	var doc struct {
		Tasks map[string]*struct {
			Type string   `yaml:"type"`
			Cwd  string   `yaml:"cwd"`
			Cmd  []string `yaml:"cmd"`
			Deps []string `yaml:"deps"`
		} `yaml:"tasks"`
	}
	if yaml.Unmarshal(b, &doc) != nil {
		return out
	}
	for path, t := range doc.Tasks {
		if t == nil || strings.HasSuffix(path, "/") {
			continue
		}
		dir := t.Cwd
		if !filepath.IsAbs(dir) && filepath.VolumeName(dir) == "" {
			dir = strings.TrimPrefix(strings.TrimPrefix(dir, ".."), "/")
			if dir == "" {
				dir = "."
			}
		}
		g := genTask{Path: path, Dir: dir, Cmd: t.Cmd, Deps: t.Deps, Job: t.Type == "job"}
		e := fragEntry{Sig: g.signature()}
		if w := portless.ParseCommand(t.Cmd); w != nil {
			e.Name = w.Name
		}
		out[path] = e
	}
	return out
}

func oldName(old map[string]fragEntry, task string) string {
	return old[task].Name
}

// ensureLoad returns dekit.yaml with a load entry for rel (a path relative to
// dekit.yaml), adding it with as small an edit as possible: a new file, an
// appended item in an existing block list, or a load: block at the end of
// the file. Every edit is re-read to check that only the entry was added;
// anything unusual is left to the user.
func ensureLoad(before, rel string) (string, error) {
	if strings.TrimSpace(before) == "" {
		return "# dekit project: https://dekit.run. Portplane's generated tasks live in " + rel + ".\nload:\n  - " + rel + "\n", nil
	}
	byHand := fmt.Errorf("add %q under load: in dekit.yaml by hand", rel)
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(before), &doc); err != nil {
		return "", fmt.Errorf("dekit.yaml is not valid YAML: %w", err)
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return "", errors.New("dekit.yaml has no top-level mapping")
	}
	top := doc.Content[0]
	if top.Style&yaml.FlowStyle != 0 {
		return "", byHand
	}
	var load *yaml.Node
	for i := 0; i+1 < len(top.Content); i += 2 {
		if top.Content[i].Value == "load" {
			load = top.Content[i+1]
		}
	}
	prev, err := loadEntries(before)
	if err != nil {
		return "", byHand
	}
	for _, e := range prev {
		if strings.TrimPrefix(e, "./") == rel {
			return before, nil
		}
	}
	text := before
	if !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	var out string
	switch {
	case load == nil:
		out = text + "load:\n  - " + rel + "\n"
	case load.Kind != yaml.SequenceNode || load.Style&yaml.FlowStyle != 0 || len(load.Content) == 0:
		return "", byHand
	default:
		last := 0
		for _, item := range load.Content {
			if l := maxLine(item); l > last {
				last = l
			}
		}
		lines := strings.SplitAfter(text, "\n")
		first := load.Content[0]
		if first.Line < 1 || first.Line > len(lines) || last > len(lines) {
			return "", byHand
		}
		// Indent the new item like the first one: up to its dash.
		head := lines[first.Line-1]
		if first.Column-1 <= len(head) {
			head = head[:first.Column-1]
		}
		dash := strings.LastIndex(head, "-")
		if dash < 0 {
			return "", byHand
		}
		entry := strings.Repeat(" ", dash) + "- " + rel + "\n"
		out = strings.Join(lines[:last], "") + entry + strings.Join(lines[last:], "")
	}
	got, err := loadEntries(out)
	if err != nil || len(got) != len(prev)+1 || got[len(got)-1] != rel {
		return "", byHand
	}
	for i := range prev {
		if got[i] != prev[i] {
			return "", byHand
		}
	}
	return out, nil
}

// loadEntries lists the files a dekit.yaml loads, in order.
func loadEntries(text string) ([]string, error) {
	var doc struct {
		Load []yaml.Node `yaml:"load"`
	}
	if err := yaml.Unmarshal([]byte(text), &doc); err != nil {
		return nil, err
	}
	var out []string
	for _, n := range doc.Load {
		switch n.Kind {
		case yaml.ScalarNode:
			out = append(out, n.Value)
		case yaml.MappingNode:
			file := ""
			for i := 0; i+1 < len(n.Content); i += 2 {
				if n.Content[i].Value == "file" {
					file = n.Content[i+1].Value
				}
			}
			out = append(out, file)
		default:
			return nil, errors.New("unexpected load entry")
		}
	}
	return out, nil
}

func maxLine(n *yaml.Node) int {
	m := n.Line
	for _, c := range n.Content {
		if l := maxLine(c); l > m {
			m = l
		}
	}
	return m
}
