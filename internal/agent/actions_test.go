func TestTaskActionsAndRemove(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root+"/dekit.yaml", "load:\n  - .portplane/tasks.yaml\ntasks:\n  shop/web:\n    cmd: [node, web.js]\n")
	frag := filepath.Join(root, ".portplane", "tasks.yaml")
	if err := os.MkdirAll(filepath.Dir(frag), 0o755); err != nil {
		t.Fatal(err)
	}
	writeFile(t, frag, "# Generated by Portplane.\ntasks:\n  shop/api:\n    cmd: [node, api.js]\n\n  shop/docs:\n    cmd: [node, docs.js]\n")
	dk := &fakeDekit{
		runners: []dekit.RunnerRecord{{PID: 100, Root: root, Running: true}},
		states: map[string][]dekit.TaskState{root: {
			{Path: "shop/web", Kind: "service", State: "ready"},
			{Path: "shop/api", Kind: "service", State: "ready"},
			{Path: "shop/docs", Kind: "service", State: "idle"},
			{Path: "tmp/migrate", Kind: "service", State: "running"},
		}},
	}
	l := NewLocal(Options{Folders: []string{root}, Dekit: dk, Portless: fakeRouter{routes: []portless.Route{}}, OS: fakeOS{}})
	ctx := context.Background()
	snap := l.collect(ctx)
	apps := map[string]model.App{}
	for _, a := range snap.Apps {
		apps[a.Task] = a
	}
	if !apps["tmp/migrate"].Dynamic || apps["shop/web"].Dynamic || !apps["shop/api"].Portplane || apps["shop/web"].Portplane {
		t.Fatalf("origins: %+v", apps)
	}
	act := func(task string, v model.Verb) error {
		return l.Act(ctx, model.Target{Machine: "local", Runner: root, Task: task}, v)
	}
	for _, v := range []model.Verb{model.VerbKill, model.VerbVeto, model.VerbForceRestart} {
		if err := act("shop/web", v); err != nil {
			t.Fatal(v, err)
		}
	}
	// A dynamic task leaves the runner; a fragment task also leaves the file.
	if err := act("tmp/migrate", model.VerbRemove); err != nil {
		t.Fatal(err)
	}
	if err := act("shop/api", model.VerbRemove); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(frag)
	if string(b) != "# Generated by Portplane.\ntasks:\n  shop/docs:\n    cmd: [node, docs.js]\n" {
		t.Fatalf("fragment after remove:\n%s", b)
	}
	// A task the user wrote is theirs: Portplane does not remove it.
	if err := act("shop/web", model.VerbRemove); err == nil || !strings.Contains(err.Error(), "dekit.yaml") {
		t.Fatalf("hand-written task removed: %v", err)
	}
	if err := l.Act(ctx, model.Target{Machine: "local", Runner: root, Prefix: "shop/"}, model.VerbRemove); err == nil {
		t.Fatal("remove is one app at a time")
	}
	want := []string{"kill shop/web", "veto shop/web", "kill shop/web", "start shop/web", "rm tmp/migrate", "rm shop/api"}
	if !reflect.DeepEqual(dk.acted, want) {
		t.Fatalf("acted\n got %v\nwant %v", dk.acted, want)
	}
}

func TestGroupTargetsForNewVerbs(t *testing.T) {
	group := []model.App{
		{Task: "shop/web", Kind: "service", State: model.StateOn},
		{Task: "shop/api", Kind: "service", State: model.StateOff},
		{Task: "shop/install", Kind: "job", State: model.StateDone},
	}
	if got := groupTargets(group, "shop/", model.VerbVeto, nil); !reflect.DeepEqual(got, []string{"shop/**"}) {
		t.Errorf("veto: %v", got)
	}
	if got := groupTargets(group, "", model.VerbKill, nil); !reflect.DeepEqual(got, []string{"shop/web", "shop/api", "shop/install"}) {
		t.Errorf("kill: %v", got)
	}
	if got := groupTargets(group, "", model.VerbForceRestart, nil); !reflect.DeepEqual(got, []string{"shop/web"}) {
		t.Errorf("force-restart: %v", got)
	}
	for _, v := range []model.Verb{"kill", "veto", "rm", "force-restart", "start"} {
		if !v.Valid() {
			t.Errorf("%s invalid", v)
		}
	}
	if model.Verb("explode").Valid() {
		t.Error("unknown verb valid")
	}
}
