import { cleanName } from "../lib/setup";
import { ApiError } from "./errors";
import type { App, AppProposal, FileChange, Proposal, SetupCheck, SetupOverrides, Tools } from "./types";

// A fake scanner for `?mock` and tests: a pnpm monorepo with a git worktree,
// an npm project with a Sanity studio, and (when the folder already has
// config) a hand-written task, a changed task and a removed one. Files are
// rendered the way internal/setup renders them, so the diffs look real.

const FRAGMENT = ".portplane/tasks.yaml";
const HEADER = `# Generated by Portplane (https://github.com/akamachinecode/portplane).
# Every scan rewrites this file and keeps the portless names you change here.
# To own a task completely, move it into dekit.yaml: Portplane then leaves it alone.
`;
const AGENT_ENV = ["AI_AGENT", "AGENT", "CLAUDECODE", "CODEX_THREAD_ID", "CURSOR_TRACE_ID"];
const STALE = "the folder changed since this proposal was made: scan again and review the new changes";

/** "fresh": the folder has no dekit config yet. "existing": it was set up before and has moved on since. */
export type SetupVariant = "fresh" | "existing";

interface Pkg {
  task: string;
  project: string;
  worktree?: string;
  dir: string; // relative to the folder
  package?: string;
  framework: string;
  pm: "pnpm" | "npm";
  main?: boolean;
  hardPort?: string;
  /** Configured by hand in dekit.yaml (existing variant only). */
  manual?: boolean;
}

interface Checkout {
  project: string;
  worktree?: string;
  dir: string;
  pm: "pnpm" | "npm";
  pkgs: Pkg[];
}

function checkouts(variant: SetupVariant): Checkout[] {
  const existing = variant === "existing";
  const mono = (worktree: string | undefined, dir: string): Checkout => {
    const prefix = worktree ? `my-monorepo/${worktree}/` : "my-monorepo/";
    const pkgs: Pkg[] = [
      { task: `${prefix}web`, project: "my-monorepo", worktree, dir: `${dir}/apps/web`, package: "@my-monorepo/web", framework: "next", pm: "pnpm", main: true },
      { task: `${prefix}api`, project: "my-monorepo", worktree, dir: `${dir}/apps/api`, package: "@my-monorepo/api", framework: "node", pm: "pnpm" },
      { task: `${prefix}admin`, project: "my-monorepo", worktree, dir: `${dir}/apps/admin`, package: "@my-monorepo/admin", framework: "vite", pm: "pnpm", hardPort: "4516" },
    ];
    if (!worktree) {
      pkgs.push({ task: `${prefix}docs`, project: "my-monorepo", dir: `${dir}/apps/docs`, package: "@my-monorepo/docs", framework: "astro", pm: "pnpm", manual: existing });
    }
    return { project: "my-monorepo", worktree, dir, pm: "pnpm", pkgs };
  };
  return [
    mono(undefined, "my-monorepo"),
    mono("checkout", "my-monorepo-checkout"),
    {
      project: "blog",
      dir: "blog",
      pm: "npm",
      pkgs: [
        { task: "blog/web", project: "blog", dir: "blog", package: "blog", framework: "astro", pm: "npm", main: true },
        { task: "blog/studio", project: "blog", dir: "blog/studio", package: "blog-studio", framework: "sanity", pm: "npm" },
      ],
    },
  ];
}

function defaultName(p: Pkg): string {
  const app = p.task.split("/").pop()!;
  const wt = p.worktree ? `${p.worktree}.` : "";
  return p.main ? `${wt}${p.project}`.replace(/\.$/, "") : `${app}.${wt}${p.project}`;
}

function devCommand(p: Pkg, name: string): { argv: string[]; notes: string[] } {
  const exec = (...args: string[]) => (p.pm === "npm" ? ["npx", "--no-install", ...args] : [p.pm, "exec", ...args]);
  if (p.framework === "sanity") {
    return {
      argv: ["portless", name, "portplane", "port-exec", "--", ...exec("sanity", "dev", "--host", "{HOST}", "--port", "{PORT}")],
      notes: ["Sanity ignores PORT, so the port is passed explicitly with portplane port-exec."],
    };
  }
  const notes: string[] = [];
  let inner = [p.pm, "run", "dev"];
  if (p.hardPort) {
    inner = exec(p.framework === "next" ? "next" : p.framework, "dev");
    notes.push(`The dev script pins port ${p.hardPort}, which would win over portless; Portplane calls the framework directly instead.`);
  }
  if (p.framework === "node") notes.push("Unknown dev server: it must listen on the PORT variable for its URL to work.");
  return { argv: ["portless", name, ...inner], notes };
}

interface Task {
  path: string;
  folder?: boolean;
  label?: string;
  job?: boolean;
  dir?: string;
  cmd?: string[];
  deps?: string[];
  comment?: string;
}

const q = (s: string) => JSON.stringify(s);
const flow = (items: string[]) => `[${items.map(q).join(", ")}]`;
const sig = (t: Task) => JSON.stringify([t.job ?? false, t.dir, t.cmd, t.deps]);

function render(tasks: Task[]): string {
  let out = HEADER;
  if (tasks.length === 0) return out + "tasks: {}\n";
  out += "tasks:\n";
  const env = `{${AGENT_ENV.map((k) => `${k}: null`).join(", ")}}`;
  for (const t of tasks) {
    if (t.folder) {
      out += `  ${t.path}:\n`;
      continue;
    }
    if (t.comment) out += `  # ${t.comment}\n`;
    out += `  ${t.path}:\n`;
    if (t.label) out += `    label: ${q(t.label)}\n`;
    if (t.job) out += "    type: job\n";
    out += `    cwd: ${q(t.dir === "." ? ".." : `../${t.dir}`)}\n`;
    out += `    cmd: ${flow(t.cmd ?? [])}\n`;
    if (t.deps?.length) out += `    deps: ${flow(t.deps)}\n`;
    out += `    env: ${env}\n`;
  }
  return out;
}

function installCmd(pm: Checkout["pm"]): string[] {
  return pm === "pnpm" ? ["pnpm", "install", "--frozen-lockfile"] : ["npm", "install", "--no-audit", "--no-fund"];
}

/** FNV-1a, enough to tell two proposals apart. */
function digestOf(files: FileChange[]): string {
  let h = 0x811c9dc5;
  for (const f of files) {
    for (const ch of `${f.path}\0${f.before}\0${f.after}\0`) {
      h ^= ch.charCodeAt(0);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
  }
  return h.toString(16).padStart(8, "0");
}

const DEKIT_EXISTING = `# Tasks written by hand. Portplane leaves them alone.
tasks:
  my-monorepo/docs:
    cwd: my-monorepo/apps/docs
    cmd: [portless, docs.my-monorepo, pnpm, run, dev]
  db:
    cmd: [docker, compose, up, postgres]

load:
  - tasks/*.yaml
`;

/** Adds the load entry like ensureLoad in Go, for the shapes this mock produces. */
function ensureLoad(before: string): string {
  if (before.trim() === "") return `# dekit project: https://dekit.run. Portplane's generated tasks live in ${FRAGMENT}.\nload:\n  - ${FRAGMENT}\n`;
  if (before.includes(FRAGMENT)) return before;
  if (before.includes("load:\n  - tasks/*.yaml\n")) return before.replace("  - tasks/*.yaml\n", `  - tasks/*.yaml\n  - ${FRAGMENT}\n`);
  return `${before.endsWith("\n") ? before : before + "\n"}load:\n  - ${FRAGMENT}\n`;
}

interface Generated {
  proposal: Proposal;
  tasks: Task[];
  names: Map<string, string>;
}

export interface MockSetup {
  check(tools: Tools): SetupCheck;
  scan(folder: string, overrides: SetupOverrides): Proposal;
  /** Writes like the server: refuses a digest that no longer matches (409). */
  apply(folder: string, digest: string, overrides: SetupOverrides): { written: string[]; tasks: App[] };
  /** Simulates someone editing the folder after a scan: the next apply gets a 409. */
  touch(): void;
}

export function createMockSetup(variant: SetupVariant, root: string): MockSetup {
  let fragment = "";
  let dekitYaml = "";
  let prevTasks = new Map<string, { sig: string; name?: string }>();

  if (variant === "existing") {
    // What an earlier setup wrote: no worktree yet, admin's script did not
    // pin a port, the studio was renamed by hand, and a legacy app existed.
    const old = generate({}, "previous");
    fragment = render(old.tasks);
    prevTasks = taskIndex(old.tasks, old.names);
    dekitYaml = DEKIT_EXISTING;
  }

  function taskIndex(tasks: Task[], names: Map<string, string>) {
    return new Map(tasks.filter((t) => !t.folder).map((t) => [t.path, { sig: sig(t), name: names.get(t.path) }]));
  }

  function generate(ov: SetupOverrides, mode: "current" | "previous" = "current"): Generated {
    const previous = mode === "previous";
    const apps: AppProposal[] = [];
    const tasks: Task[] = [];
    const names = new Map<string, string>();
    for (const co of checkouts(variant)) {
      if (previous && co.worktree) continue;
      if (!tasks.some((t) => t.path === `${co.project}/`)) tasks.push({ path: `${co.project}/`, folder: true });
      const prefix = co.worktree ? `${co.project}/${co.worktree}/` : `${co.project}/`;
      const install: Task = {
        path: `${prefix}install`,
        label: "install",
        job: true,
        dir: co.dir,
        cmd: installCmd(co.pm),
        comment: "One install per checkout before any app starts (field notes: parallel installs fail).",
      };
      const appTasks: Task[] = [];
      const pkgs = previous && co.project === "my-monorepo" ? [...co.pkgs, { ...co.pkgs[1], task: `${prefix}legacy`, dir: `${co.dir}/apps/legacy`, package: "@my-monorepo/legacy" }] : co.pkgs;
      for (const pkg of pkgs) {
        let name = defaultName(pkg);
        if (previous && pkg.task === "blog/studio") name = "cms.blog"; // renamed by hand in the fragment; scans keep it
        const kept = prevTasks.get(pkg.task)?.name;
        if (kept) name = kept;
        const typed = ov.names?.[pkg.task];
        if (typed && cleanName(typed)) name = cleanName(typed);
        const ap: AppProposal = {
          task: pkg.task,
          project: pkg.project,
          worktree: pkg.worktree,
          name,
          hostname: `${name}.localhost`,
          dir: pkg.dir,
          package: pkg.package,
          framework: pkg.framework,
          packageManager: pkg.pm,
          command: [],
          status: "new",
          skipped: false,
        };
        if (pkg.manual) {
          ap.status = "manual";
          ap.skipped = true;
          ap.notes = ["Already configured by hand in dekit.yaml; Portplane leaves it alone."];
          apps.push(ap);
          continue;
        }
        const { argv, notes } = devCommand(previous ? { ...pkg, hardPort: undefined } : pkg, name);
        ap.command = argv;
        if (notes.length) ap.notes = notes;
        if (ov.skip?.[pkg.task]) {
          ap.status = "skipped";
          ap.skipped = true;
          apps.push(ap);
          continue;
        }
        apps.push(ap);
        names.set(pkg.task, name);
        appTasks.push({
          path: pkg.task,
          dir: pkg.dir,
          cmd: argv,
          deps: [install.path],
          comment: `${pkg.package ?? pkg.dir} (${pkg.framework}) at https://${name}.localhost`,
        });
      }
      if (appTasks.length === 0) continue;
      if (co.worktree) tasks.push({ path: prefix, folder: true });
      tasks.push(install, ...appTasks);
    }

    const after = render(tasks);
    const dekitAfter = ensureLoad(dekitYaml);
    const files: FileChange[] = [
      { path: `${root}/${FRAGMENT}`, before: fragment, after, created: fragment === "", changed: fragment !== after },
      { path: `${root}/dekit.yaml`, before: dekitYaml, after: dekitAfter, created: dekitYaml === "", changed: dekitYaml !== dekitAfter },
    ];

    const now = taskIndex(tasks, names);
    const change = { added: [] as string[], changed: [] as string[], removed: [] as string[] };
    for (const [path, t] of now) {
      const old = prevTasks.get(path);
      if (!old) change.added.push(path);
      else if (old.sig !== t.sig) change.changed.push(path);
    }
    for (const path of prevTasks.keys()) if (!now.has(path)) change.removed.push(path);
    change.removed.sort();
    for (const a of apps) {
      if (a.skipped) continue;
      const old = prevTasks.get(a.task);
      a.status = !old ? "new" : old.sig !== now.get(a.task)?.sig ? "changed" : "unchanged";
    }

    const warnings = [
      "my-monorepo: apps on sibling subdomains share a login only with a parent cookie domain (my-monorepo.localhost). Check your auth library's cross-subdomain cookie setting.",
      "blog: add the new https://*.blog.localhost origins to your CMS's CORS settings, or its API calls will fail.",
    ];
    return { proposal: { folder: root, apps, warnings, change, files, digest: digestOf(files) }, tasks, names };
  }

  const checkFolder = (folder: string) => {
    if (folder.replace(/\/$/, "") !== root) throw new ApiError("set up only folders Portplane watches: add it in Settings first", 400);
  };

  return {
    check(tools) {
      const reqs: SetupCheck["requirements"] = [
        { id: "node", name: "Node.js 24 or later", why: "portless runs on Node.js 24+.", ok: true, version: "v24.11.0", docs: "https://nodejs.org", privilege: false },
        {
          id: "dekit",
          name: "dekit",
          why: "Runs and supervises your dev servers; Portplane writes its config and starts and stops tasks through it.",
          ok: !!tools.dekit,
          version: tools.dekit,
          docs: "https://dekit.run",
          privilege: false,
          ...(tools.dekit ? {} : { problem: "dekit was not found on PATH.", commands: ["curl -fsSL https://dekit.run/install.sh | sh"] }),
        },
        {
          id: "portless",
          name: "portless",
          why: "Gives every dev server a stable https://<name>.localhost URL, whatever port it lands on.",
          ok: !!tools.portless,
          version: tools.portless,
          docs: "https://github.com/vercel-labs/portless",
          privilege: false,
          ...(tools.portless ? {} : { problem: "portless was not found on PATH.", commands: ["npm install -g portless"] }),
        },
        {
          id: "proxy",
          name: "portless proxy on port 443",
          why: "Serves the .localhost URLs over HTTPS with a trusted local certificate, and starts with your computer.",
          ok: tools.proxyRunning,
          privilege: true,
          ...(tools.proxyRunning ? {} : { problem: "The portless proxy is not running.", commands: ["sudo portless service install"] }),
        },
        {
          id: "portplane",
          name: "portplane on PATH",
          why: "A few generated tasks (Sanity, Remotion) call `portplane port-exec` to pass the port.",
          ok: false, // so the mock shows a missing tool that doesn't block setup
          privilege: false,
          problem: "The portplane binary is not on PATH; tasks that use port-exec would not start.",
        },
      ];
      const ok = (id: string) => reqs.find((r) => r.id === id)!.ok;
      return { requirements: reqs, ready: ok("node") && ok("dekit") && ok("portless") };
    },
    scan(folder, overrides) {
      checkFolder(folder);
      return generate(overrides).proposal;
    },
    apply(folder, digest, overrides) {
      checkFolder(folder);
      const g = generate(overrides);
      if (!digest || digest !== g.proposal.digest) throw new ApiError(STALE, 409);
      const written = g.proposal.files.filter((f) => f.changed).map((f) => f.path);
      fragment = g.proposal.files[0].after;
      dekitYaml = g.proposal.files[1].after;
      prevTasks = taskIndex(g.tasks, g.names);
      const tasks: App[] = g.tasks
        .filter((t) => !t.folder)
        .map((t, order) => {
          const name = g.names.get(t.path);
          return {
            id: `${root}#${t.path}`,
            runner: root,
            task: t.path,
            label: t.label ?? t.path.split("/").pop()!,
            kind: t.job ? "job" : "service",
            project: t.path.split("/")[0],
            worktree: g.proposal.apps.find((a) => a.task === t.path)?.worktree ?? (t.path.split("/").length > 2 ? t.path.split("/")[1] : undefined),
            dir: `${root}/${t.dir}`,
            command: t.cmd,
            deps: t.deps,
            state: t.job ? "done" : "off",
            rawState: "stopped",
            hostname: name ? `${name}.localhost` : undefined,
            order,
          } satisfies App;
        });
      return { written, tasks };
    },
    touch() {
      dekitYaml = dekitYaml
        ? dekitYaml.replace("tasks:\n", "tasks:\n  redis:\n    cmd: [docker, compose, up, redis]\n")
        : "# Written by hand while the review was open.\ntasks:\n  db:\n    cmd: [docker, compose, up, postgres]\n";
    },
  };
}
