function render(p: MockProject, file: MockFile): string {
  if (file.text !== undefined) return file.text;
  if (!file.exists) return "";
  let out = file.header;
  if (file.role === "main") {
    for (const [k, v] of Object.entries(p.settings)) out += toYaml({ [k]: v });
    if (p.load.length) out += toYaml({ load: p.load });
  }
  const tasks = p.tasks.filter((t) => t.file === file.path);
  if (tasks.length) {
    out += "tasks:\n";
    for (const t of tasks) out += Object.keys(t.values).length ? `  ${t.key}:\n${toYaml(t.values, 4)}` : `  ${t.key}:\n`;
  } else if (file.role === "portplane") out += "tasks: {}\n";
  return out;
}

function digest(text: string): string {
  let h = 0;
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) | 0;
  return `mock-${(h >>> 0).toString(16)}`;
}

function projectConfig(p: MockProject): ProjectConfig {
  const files: ConfigFileInfo[] = p.files.map((f) => {
    const content = render(p, f);
    const rel = p.root === "host" ? "dekit.yaml" : f.path.slice(ROOT.length + 1);
    return { path: f.path, rel, role: f.role, exists: f.exists, digest: f.exists ? digest(content) : "", content, editable: true };
  });
  const tasks: TaskEntry[] = p.tasks.map((t, i) => ({
    path: t.key.replace(/\/$/, ""),
    key: t.key,
    file: t.file,
    folder: t.key.endsWith("/"),
    line: i + 3,
    values: structuredClone(t.values),
    editable: true,
  }));
  const text: Record<string, string> = {};
  for (const [k, v] of Object.entries(p.settings)) text[k] = toYaml({ [k]: v });
  return {
    root: p.root,
    file: p.files[0].path,
    files,
    tasks,
    load: p.load.map((file, i) => ({ file, line: 4 + i })),
    settings: structuredClone(p.settings),
    text,
    fragment: `${p.root}/.portplane/tasks.yaml`,
    warnings: [],
  };
}

function parseEntryText(text: string): YamlValue {
  // Mock only: show the text as written, keep the value as JSON when it parses.
  const body = text.replace(/^[^:\n]+:\s*/, "").trim();
  try {
    return JSON.parse(body) as YamlValue;
  } catch {
    return body;
  }
}

/** Applies edits to the structured project; returns the tasks they touched. */
function applyOps(p: MockProject, file: string, ops: EditOp[]): string[] {
  const touched: string[] = [];
  const f = p.files.find((x) => x.path === file);
  if (!f) throw new ApiError(`${file} isn't part of this project's dekit config`, 400);
  const taskAt = (path: string[]) => {
    if (path[0] !== "tasks") return undefined;
    const t = p.tasks.find((x) => x.file === file && x.key === path[1]);
    if (!t) throw new ApiError(`tasks.${path[1]}: not found`, 400);
    return t;
  };
  for (const op of ops) {
    switch (op.op) {
      case "set":
      case "unset": {
        if (op.path[0] === "tasks") {
          const t = taskAt(op.path)!;
          if (op.path.length === 2) {
            const v = t.values[op.key];
            if (v && typeof v === "object" && !Array.isArray(v) && "$js" in v) throw new ApiError("this part of the file can't be edited from Portplane; open it in your editor", 422);
            if (op.op === "set") t.values[op.key] = op.value;
            else delete t.values[op.key];
            touched.push(t.key);
          }
        } else if (op.path.length === 0) {
          if (op.op === "set") p.settings[op.key] = op.value;
          else delete p.settings[op.key];
        } else {
          const m = (p.settings[op.path[0]] ?? {}) as Record<string, YamlValue>;
          if (op.op === "set") m[op.key] = op.value;
          else delete m[op.key];
          p.settings[op.path[0]] = m;
        }
        break;
      }
      case "insert": {
        if (op.path[0] !== "tasks") {
          p.settings[op.key] = op.value;
          break;
        }
        if (p.tasks.some((t) => t.key === op.key && t.file === file)) throw new ApiError(`tasks already has "${op.key}"`, 400);
        const nt = task(op.key, file, structuredClone(op.value) as Record<string, YamlValue>);
        const anchor = op.after ?? op.before;
        const i = anchor ? p.tasks.findIndex((t) => t.key === anchor && t.file === file) : -1;
        if (i >= 0) p.tasks.splice(op.after ? i + 1 : i, 0, nt);
        else p.tasks.push(nt);
        f.exists = true;
        touched.push(op.key);
        break;
      }
      case "delete":
        if (op.path[0] === "tasks") {
          const t = taskAt(op.path)!;
          p.tasks = p.tasks.filter((x) => x !== t);
          touched.push(t.key);
        } else delete p.settings[op.path[0]];
        break;
      case "rename": {
        const t = taskAt(op.path)!;
        if (p.tasks.some((x) => x.key === op.to)) throw new ApiError(`"${op.to}" already exists`, 400);
        touched.push(t.key, op.to);
        t.key = op.to;
        break;
      }
      case "move": {
        const t = taskAt(op.path)!;
        p.tasks = p.tasks.filter((x) => x !== t);
        const anchor = op.after ?? op.before;
        const i = p.tasks.findIndex((x) => x.key === anchor && x.file === file);
        p.tasks.splice(op.after ? i + 1 : Math.max(0, i), 0, t);
        break;
      }
      case "text":
        if (op.path[0] === "tasks") taskAt(op.path)!.values = { note: parseEntryText(op.text) } as Record<string, YamlValue>;
        else p.settings[op.path[0]] = parseEntryText(op.text);
        break;
      case "replace":
        f.text = op.text;
        break;
      case "load":
        if (!p.load.includes(op.file)) p.load.push(op.file);
        break;
    }
  }
  return touched;
}

/** dekit's word for a mock app's state. */
function rawState(a: App): string {
  switch (a.state) {
    case "on":
      return "ready";
    case "starting":
      return a.kind === "job" ? "running" : "starting";
    case "stopping":
      return "stopping";
    case "failed":
      return a.detail?.includes("restarting") ? "backoff" : "exited";
    case "done":
      return "done";
    default:
      return "idle";
  }
}

function mockWhy(ms: MachineSnapshot, a: App): Why {
  const same = ms.apps.filter((x) => x.runner === a.runner);
  const byTask = new Map(same.map((x) => [x.task, x]));
  const state = rawState(a);
  const deps = (a.deps ?? []).map((d) => {
    const dep = byTask.get(d);
    const s = dep ? rawState(dep) : "idle";
    return { path: d, state: s, exit_code: s === "done" ? 0 : undefined, wanted: true, satisfied: s === "ready" || s === "done" };
  });
  const requiredBy = same.filter((x) => x.deps?.includes(a.task)).map((x) => x.task);
  const vetoed = a.detail === "kept stopped";
  const alive = state !== "idle" && state !== "done" && state !== "exited";
  return {
    id: a.order + 2,
    path: a.task,
    state,
    exit_code: state === "exited" ? 3 : state === "done" ? 0 : undefined,
    reason: a.detail?.includes("not ready") ? "ready_timeout" : undefined,
    wanted: alive || state === "exited",
    supported: deps.every((d) => d.satisfied),
    vetoed,
    pinned: alive && requiredBy.length === 0 && a.kind !== "job",
    required_by: requiredBy,
    deps,
    attempts: state === "backoff" ? 2 : 0,
  };
}

