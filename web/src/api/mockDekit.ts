      const lines = content.split("\n");
      for (let i = 0; i < lines.length; i++) {
        if (/^\s*taks:/.test(lines[i])) problems.push({ path: "taks", line: i + 1, message: '"taks" isn\'t a dekit.yaml setting' });
        if (/\t/.test(lines[i])) problems.push({ path: "", line: i + 1, message: "not valid YAML: found a tab character where indentation is expected" });
        if (/autorestart:\s*(?!never|on-failure|always)\S+/.test(lines[i])) problems.push({ path: "", line: i + 1, message: "autorestart: should be one of never, on-failure, always" });
      }
