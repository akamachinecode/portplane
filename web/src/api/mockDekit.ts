// ---- a tiny YAML writer (mock only) ----

function scalar(v: YamlValue): string {
  if (v === null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "object" && !Array.isArray(v) && "$js" in v) return `!js '${String(v.$js).replace(/'/g, "''")}'`;
  const s = String(v);
  return /^[\w./@+-][\w ./@+:-]*$/.test(s) && !/^(true|false|null|yes|no|\d+(\.\d+)?)$/i.test(s) && !s.endsWith(":") && !/: /.test(s) ? s : JSON.stringify(s);
}

function isPlain(v: YamlValue): boolean {
  return v === null || typeof v !== "object" || (!Array.isArray(v) && "$js" in v);
}

function flow(v: YamlValue): string | null {
  if (Array.isArray(v) && v.every(isPlain)) return `[${v.map(scalar).join(", ")}]`;
  if (v && typeof v === "object" && !Array.isArray(v) && !("$js" in v) && Object.values(v).every(isPlain) && Object.keys(v).length <= 4) {
    const s = `{${Object.entries(v).map(([k, x]) => `${k}: ${scalar(x)}`).join(", ")}}`;
    return s.length <= 70 ? s : null;
  }
  return null;
}

export function toYaml(map: Record<string, YamlValue>, indent = 0): string {
  const pad = " ".repeat(indent);
  let out = "";
  for (const [k, v] of Object.entries(map)) {
    if (isPlain(v)) out += `${pad}${k}: ${scalar(v)}\n`;
    else if (flow(v)) out += `${pad}${k}: ${flow(v)}\n`;
    else if (Array.isArray(v)) out += `${pad}${k}:\n${v.map((x) => `${pad}  - ${isPlain(x) ? scalar(x) : (flow(x) ?? JSON.stringify(x))}\n`).join("")}`;
    else out += `${pad}${k}:\n${toYaml(v as Record<string, YamlValue>, indent + 2)}`;
  }
  return out;
}

